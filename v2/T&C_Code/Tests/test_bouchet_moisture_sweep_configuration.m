function test_bouchet_moisture_sweep_configuration
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Static and case-matrix checks for the Bouchet control moisture sweep.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
v2_dir = fileparts(code_dir);
repo_root = fileparts(v2_dir);
campaign = 'Kantola_5yr_1D_Control_Moisture_Sweep_R2025a_Bouchet';
runtime_dir = fullfile(repo_root,'runtime',campaign);
addpath(runtime_dir);

required = {'Kantola_Moisture_Sweep_Cases.m', ...
    'Run_Bouchet_Moisture_Sweep_Task.m', ...
    'Validate_Bouchet_Moisture_Sweep.m', ...
    'Summarize_Bouchet_Moisture_Sweep.m', ...
    'Bouchet_Assert_Moisture_Sweep_Provenance.m', ...
    'Kantola_Moisture_Sweep_Moisture_Diagnostics.m', ...
    'Bouchet_Fingerprint_Digest.m', ...
    'submit_kantola_moisture_sweep.sbatch', ...
    'submit_kantola_moisture_sweep.sh','README.md'};
for k = 1:numel(required)
    assert(isfile(fullfile(runtime_dir,required{k})), ...
        'Missing Bouchet moisture-sweep file %s.',required{k});
end

cases = Kantola_Moisture_Sweep_Cases;
assert(numel(cases) == 6 && isequal([cases.id],1:6), ...
    'The sweep must contain six Slurm array cases.');
assert(isequal([cases.Pcla],[0.35 0.35 0.35 0.12 0.12 0.12]) && ...
       isequal([cases.Psan],[0.10 0.10 0.10 0.22 0.22 0.22]), ...
    'The workbook and Pihlap texture blocks are wrong.');
assert(isequal([cases.KNmaxd],repmat([0.0064 0.0032 0.0016],1,2)), ...
    'The denitrification-rate grid is wrong.');
assert(numel(unique({cases.tag})) == 6, ...
    'Every sweep case needs a distinct result directory.');
expected_logKH = [4.71627429367 3.61627429367 8.10254858734 ...
    8.41854858734 12.918822881];
assert(all(strcmp({cases.exchange_scheme},'appelo')) && ...
       isequal([cases.AppeloAlpha],1.3*ones(1,6)) && ...
       all(cellfun(@(x) isequal(x,expected_logKH),{cases.AppeloLogKH})), ...
    'Every sweep case must pin the effective Kantola Appelo constants.');

wrapper = fileread(fullfile(runtime_dir,'Run_Bouchet_Moisture_Sweep_Task.m'));
assert(contains(wrapper,'Run_Subfield_Worker(10') && ...
       contains(wrapper,"'Pcla',case_cfg.Pcla") && ...
       contains(wrapper,"'Psan',case_cfg.Psan") && ...
       contains(wrapper,"'KNmaxd',case_cfg.KNmaxd") && ...
       contains(wrapper,"'AppeloAlpha',case_cfg.AppeloAlpha") && ...
       contains(wrapper,"'AppeloLogKH',case_cfg.AppeloLogKH"), ...
    'The Bouchet worker does not apply the complete runtime case.');
assert(contains(wrapper,'Bouchet_Acquire_Run_Lock') && ...
       contains(wrapper,'Bouchet_Check_Existing_Result') && ...
       contains(wrapper,'validation_stamp.txt') && ...
       contains(wrapper,'SourceChangedDuringRun'), ...
    'The worker is missing a production safety gate.');
assert(contains(wrapper,'Bouchet_Assert_Moisture_Sweep_Provenance') && ...
       contains(wrapper,'stamp_digest') && contains(wrapper,'start_date'), ...
    'Existing sweep results are not checked against their complete identity.');

batch = fileread(fullfile(runtime_dir,'submit_kantola_moisture_sweep.sbatch'));
assert(contains(batch,'#SBATCH --array=1-6%6') && ...
       contains(batch,'#SBATCH --constraint=cpumodel:9575f') && ...
       contains(batch,'#SBATCH --cpus-per-task=1') && ...
       contains(batch,'#SBATCH --mem=8G') && ...
       contains(batch,'#SBATCH --open-mode=append') && ...
       contains(batch,'matlab -singleCompThread -batch'), ...
    'The Slurm array or single-thread resource contract is wrong.');
assert(contains(batch,'TC_REBUILD_EQUIVALENCE') && ...
       contains(batch,'TC_VALIDATE_ONLY') && ...
       contains(batch,'TC_SUMMARIZE_ONLY') && ...
       contains(batch,'TC_CKPT_MINUTES=30') && ...
       contains(batch,'unset TC_CKPT_FORCE_RESUME'), ...
    'The baseline, validation or checkpoint gate is missing.');

controller = fileread(fullfile(runtime_dir,'submit_kantola_moisture_sweep.sh'));
assert(contains(controller,'afterok:') && ...
       contains(controller,'TC_REBUILD_EQUIVALENCE=1') && ...
       contains(controller,'TC_VALIDATE_ONLY=1') && ...
       contains(controller,'TC_SUMMARIZE_ONLY=1') && ...
       contains(controller,'--array=1-6%6') && ...
       ~contains(controller,'--hold'), ...
    'The submission dependency graph is wrong.');
audit_runtime = {'runtime/submit_bouchet_all_12.sh', ...
    'runtime/bouchet_all_12_package_manifest.txt', ...
    'runtime/Kantola_5yr_1D_Runs10to12_ScheduleFix_R2025a_Bouchet', ...
    'runtime/Kantola_5yr_2D_Runs01to09_DenitPH7p8_Alpha1p3_Bouchet'};
for k = 1:numel(audit_runtime)
    assert(contains(controller,audit_runtime{k}), ...
        'Submission preflight omits audit dependency %s.',audit_runtime{k});
end
for entry_point = {'Run_Bouchet_Moisture_Sweep_Task.m', ...
        'Validate_Bouchet_Moisture_Sweep.m', ...
        'Summarize_Bouchet_Moisture_Sweep.m', ...
        'Bouchet_Fingerprint_Digest.m', ...
        'Bouchet_Assert_Moisture_Sweep_Provenance.m', ...
        'Kantola_Moisture_Sweep_Moisture_Diagnostics.m'}
    assert(contains(controller,entry_point{1}), ...
        'Submission preflight omits %s.',entry_point{1});
end

validation = fileread(fullfile(runtime_dir,'Validate_Bouchet_Moisture_Sweep.m'));
assert(contains(validation,'run_post_legacy_equation_audit_tests(1)') && ...
       contains(validation,'test_bouchet_linux_portability(campaign_dir)') && ...
       contains(validation,'Bouchet_Write_Validation_Stamp') && ...
       contains(validation,'fingerprint_before') && ...
       contains(validation,'fingerprint_after') && ...
       contains(validation,'SourceChangedDuringValidation') && ...
       contains(validation,"contains(fingerprint_before,':missing')") && ...
       contains(validation, ...
         'PASS: Bouchet R2025a control moisture sweep validation'), ...
    'The validation job does not enforce the full R2025a gate.');
assert(contains(validation,"strcmpi(p.bulk_pH_params.scheme,'appelo')") && ...
       contains(validation,'Resolve_Appelo_Constants') && ...
       contains(validation,"'AppeloLogKH',case_cfg.AppeloLogKH"), ...
    'The smoke test does not prove that the requested Appelo route is active.');

summary_source = fileread(fullfile(runtime_dir, ...
    'Summarize_Bouchet_Moisture_Sweep.m'));
assert(contains(summary_source,"Kantola_N_Magnitude_Audit(S,'control',1826)") && ...
       contains(summary_source,'Bouchet_Assert_Moisture_Sweep_Provenance') && ...
       contains(summary_source,'Kantola_Moisture_Sweep_Moisture_Diagnostics') && ...
       contains(summary_source,'bg.pH_bulk') && ...
       contains(summary_source,'max_charge_residual_umolc_L') && ...
       contains(summary_source,'Al_CEC_scale') && ...
       contains(summary_source,'SourceChangedDuringSummary') && ...
       contains(summary_source,'writetable'), ...
    'The summarizer omits a provenance, budget or output gate.');

launcher = fileread(fullfile(v2_dir,'run','Run_One_Subfield.m'));
for token = {"'Pcla'","'Psan'","'KNmaxd'", ...
        'run_provenance.Pcla','run_provenance.Psan', ...
        'run_provenance.KNmaxd','__knmaxd', ...
        'opt.Pcla + opt.Psan <= 0'}
    assert(contains(launcher,token{1}), ...
        'Run_One_Subfield omits %s.',token{1});
end
driver = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_2D.m'));
assert(contains(driver,'knmaxd=%s') && ...
       contains(driver,'biogeo_KNmaxd{c}') && ...
       contains(driver,'run_provenance.exchange_scheme') && ...
       contains(driver,'run_provenance.AppeloAlpha') && ...
       contains(driver,'run_provenance.AppeloLogKH') && ...
       contains(driver,"strcmpi(biogeo_exchange_scheme{c},'appelo')"), ...
    'The driver omits an effective chemistry input from saved provenance.');

manifest_file = fullfile(repo_root,'runtime', ...
    'bouchet_moisture_sweep_package_manifest.txt');
assert(isfile(manifest_file), ...
    'The Bouchet deployment manifest is missing.');
manifest = fileread(manifest_file);
assert(contains(manifest,campaign) && ...
       contains(manifest,'runtime/submit_bouchet_all_12.sh') && ...
       contains(manifest,'v2/T&C_Code') && ...
       contains(manifest,'v2/run'), ...
    'The deployment manifest omits the campaign or model source.');
for k = 1:numel(audit_runtime)
    assert(contains(manifest,audit_runtime{k}), ...
        'The deployment manifest omits audit dependency %s.',audit_runtime{k});
end
attributes = fileread(fullfile(repo_root,'.gitattributes'));
assert(contains(attributes, ...
       'runtime/bouchet_moisture_sweep_package_manifest.txt text eol=lf'), ...
    'The moisture-sweep manifest must remain LF for GNU tar.');

start_date = datenum(2016,1,1); %#ok<DATNM>
p = struct('Pcla',cases(4).Pcla,'Psan',cases(4).Psan, ...
    'KNmaxd',cases(4).KNmaxd,'exchange_scheme',{{'appelo'}}, ...
    'AppeloAlpha',cases(4).AppeloAlpha, ...
    'AppeloLogKH',cases(4).AppeloLogKH, ...
    'validation_fingerprint','test-digest','matlab_release','2025a', ...
    'max_threads',1,'parallel_workers',0,'n_columns',1,'n_days',1826, ...
    'campaign',campaign,'date_start',start_date, ...
    'date_end',start_date+1826-1/24,'slurm_job_id','123', ...
    'slurm_restart_count','0','slurm_array_task_id','4');
Bouchet_Assert_Moisture_Sweep_Provenance( ...
    p,cases(4),'test-digest',campaign,1826,start_date);
bad = p;
bad.AppeloAlpha = 0.8;
assert_error(@() Bouchet_Assert_Moisture_Sweep_Provenance( ...
    bad,cases(4),'test-digest',campaign,1826,start_date), ...
    'Bouchet_Moisture_Sweep:WrongProvenance');

soil.Bio_Zs = [0.25; 0.75];
soil.Soil_Param.Ohy = [0.1; 0.1];
soil.Soil_Param.Osat = [0.8; 0.8];
O = 0.79*ones(72,2);
O(1,:) = 0.100001;
O(2:25,:) = 0.4;
O(26:49,:) = 0.6;
[wfps,fmoist] = Kantola_Moisture_Sweep_Moisture_Diagnostics( ...
    O,soil,3,'synthetic');
expected_obio = [0.100001; 0.4; 0.6];
expected_wfps = 100*expected_obio/0.8;
expected_fmoist = ((expected_obio-0.1)/0.7).^2;
assert(max(abs(wfps-expected_wfps)) <= 8*eps(max(expected_wfps)) && ...
       max(abs(fmoist-expected_fmoist)) <= 64*eps, ...
    'The summary must reproduce the exact hour-1 biogeochemistry windows.');

fprintf('PASS: Bouchet control moisture sweep configuration.\n');
end

function assert_error(f,error_id)
try
    f();
catch ME
    assert(strcmp(ME.identifier,error_id), ...
        'Expected %s, got %s.',error_id,ME.identifier);
    return
end
error('test_bouchet_moisture_sweep_configuration:NoError', ...
    'Expected %s.',error_id);
end
