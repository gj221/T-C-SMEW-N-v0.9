function test_bouchet_all_12_submission
%%% The twelve runs share one validation barrier without wasting resources.

test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
repo_root = fileparts(fileparts(code_dir));
submitter_path = fullfile(repo_root,'runtime','submit_bouchet_all_12.sh');
assert(isfile(submitter_path), ...
    'The coordinated twelve-run submission script is missing.');
submitter = fileread(submitter_path);
fingerprint_source = fileread(fullfile(code_dir, ...
    'Bouchet_Campaign_Validation_Fingerprint.m'));

assert(contains(submitter,'TC_BOUCHET_ACCOUNT') && ...
    contains(submitter,'module spider') && ~contains(submitter,'--qos'), ...
    'Submission must verify the account and MATLAB module without Priority Tier.');
first_sbatch = strfind(submitter,'sbatch --parsable');
required_block_start = strfind(submitter,'required_files=(');
required_loop_start = strfind(submitter, ...
    'for required_file in "${required_files[@]}"');
assert(~isempty(first_sbatch) && ~isempty(required_block_start) && ...
    ~isempty(required_loop_start) && required_block_start(1) < ...
    required_loop_start(1) && required_loop_start(1) < first_sbatch(1), ...
    'Required payload checks must precede the first sbatch.');
required_block = submitter(required_block_start(1):required_loop_start(1)-1);
required_payload = {'$campaign_1d','$campaign_2d', ...
    'v2/T&C_Code/Inputs/Data_Kantola.mat', ...
    'v2/T&C_Code/Inputs/Data_Kantola_BG.mat', ...
    'v2/T&C_Code/Parameters/ERW_MOD_PARAM_excel.m', ...
    'v2/T&C_Code/Tests/run_post_legacy_equation_audit_tests.m', ...
    'v2/T&C_Code/Tests/Fixtures/no3_immobilization_20190906.mat', ...
    'v2/T&C_Code/ERW_function.m', ...
    'v2/run/Run_Matrix_12.m'};
for k = 1:numel(required_payload)
    assert(contains(required_block,required_payload{k}), ...
        'Required payload check omits %s.',required_payload{k});
end
required_loop = submitter(required_loop_start(1):first_sbatch(1)-1);
required_loop_end = strfind(required_loop,sprintf('\ndone'));
assert(~isempty(required_loop_end), ...
    'The required payload check must use a closed loop.');
required_loop = required_loop(1:required_loop_end(1)+4);
assert(contains(required_loop,'[[ ! -r "$repo_root/$required_file" ]]') && ...
    contains(required_loop,'No jobs were submitted.') && ...
    contains(required_loop,'exit 2'), ...
    'An unreadable payload must stop before submission.');
assert(contains(submitter,'results_1d=') && contains(submitter,'results_2d=') && ...
    contains(submitter,'logs_1d=') && contains(submitter,'logs_2d=') && ...
    contains(submitter,'find "$state_path" -mindepth 1 -print -quit') && ...
    contains(submitter,'Use a fresh deployment root'), ...
    'The coordinated launch must reject old results, locks and validation stamps.');
assert(contains(submitter,'-L "$state_path"') && ...
    contains(submitter,'! -d "$state_path"'), ...
    'A file or symlink must not stand in for a fresh campaign directory.');
assert(contains(submitter,'unset TC_REBUILD_EQUIVALENCE TC_VALIDATE_ONLY') && ...
    contains(submitter,'${!SBATCH_@}') && ...
    contains(submitter,'unset SLURM_CLUSTERS'), ...
    'Inherited campaign modes and Slurm submission controls must be cleared.');
assert(contains(submitter,'TC_REBUILD_EQUIVALENCE=1') && ...
    count(submitter,'TC_VALIDATE_ONLY=1') == 2, ...
    'The submission graph must rebuild one baseline and run both validations.');
assert(contains(submitter, ...
    '--export=ALL,TC_REBUILD_EQUIVALENCE=0 "$campaign_2d"') && ...
    ~contains(submitter,'TC_VALIDATE_ONLY=0 "$campaign_2d"'), ...
    'The 2-D production job must leave TC_VALIDATE_ONLY unset.');
assert(contains(submitter,'validation_dependency="afterok:${baseline_job}"') && ...
    contains(submitter, ...
    'production_dependency="afterok:${validation_1d_job}:${validation_2d_job}"'), ...
    'Both production jobs must wait for both validation jobs.');
assert(count(submitter,'--dependency="$production_dependency"') == 2 && ...
    ~contains(submitter,'afterok:${production_1d_job}') && ...
    ~contains(submitter,'afterok:${production_2d_job}'), ...
    'Both production classes must become eligible together without serializing each other.');
assert(count(submitter,'--kill-on-invalid-dep=yes') == 4, ...
    'Every dependent job must terminate if its prerequisite cannot succeed.');
assert(contains(submitter, ...
    '--partition=day --ntasks=1 --cpus-per-task=6 --mem=40G --time=04:00:00'), ...
    'The concurrent four-process validation must reserve its measured worker footprint.');
assert(contains(submitter,'submitted_jobs=()') && ...
    contains(submitter,'scancel "${submitted_jobs[@]}"') && ...
    contains(submitter,'trap ''rollback $?'' ERR') && ...
    contains(submitter,'trap ''rollback 129'' HUP') && ...
    contains(submitter,'Manual cancellation required') && ...
    ~contains(submitter,'scancel "${submitted_jobs[@]}" || true'), ...
    'A partial submission must report and cancel the incomplete job graph.');
assert(contains(submitter,'sbatch --parsable --hold') && ...
    contains(submitter,'scontrol release "${submitted_jobs[@]}"') && ...
    contains(submitter,'graph_complete=1'), ...
    'Every job must remain held until the complete graph can be released.');
assert(contains(submitter,'--array=1') && ...
    contains(submitter,'submit_kantola_1d_runs_10_to_12.sbatch') && ...
    contains(submitter,'submit_kantola_2d_runs_01_to_09.sbatch'), ...
    'The graph must submit one 2-D validation element and both production classes.');
assert(contains(fingerprint_source, ...
    "fullfile(fileparts(runtime_dir),'submit_bouchet_all_12.sh')"), ...
    'Campaign provenance must include the coordinated submission graph.');

manifest_path = fullfile(repo_root,'runtime', ...
    'bouchet_all_12_package_manifest.txt');
assert(isfile(manifest_path), ...
    'The Bouchet working-tree deployment manifest is missing.');
manifest = string(strtrim(splitlines(fileread(manifest_path))));
manifest(manifest == "") = [];
for required_path = [".gitattributes","README.md", ...
        "runtime/submit_bouchet_all_12.sh", ...
        "runtime/bouchet_all_12_package_manifest.txt", ...
        "runtime/Kantola_5yr_1D_Runs10to12_ScheduleFix_R2025a_Bouchet", ...
        "runtime/Kantola_5yr_2D_Runs01to09_DenitPH7p8_Alpha1p3_Bouchet", ...
        "v2/POST_LEGACY_EQUATION_AUDIT.md", ...
        "v2/T&C_Code","v2/run","v2/audit","v2/plotting","v2/calibration", ...
        "v2/Experimental observations"]
    assert(any(manifest == required_path), ...
        'Deployment manifest omits %s.',required_path);
end
assert(~any(startsWith(manifest,["v2/SIM","v2/logs","runtime/audit","tmp"])), ...
    'Deployment manifest must omit results, logs, audit output and scratch.');

root_readme = fileread(fullfile(repo_root,'README.md'));
attributes = fileread(fullfile(repo_root,'.gitattributes'));
assert(contains(root_readme,"--exclude='slurm_*.out'") && ...
    contains(root_readme,"--exclude='slurm_*.err'"), ...
    'The archive command must omit generated Slurm output from runbooks.');
assert(contains(root_readme,"tar --version | grep -Fq 'GNU tar'") && ...
    contains(root_readme,'GNU tar is required'), ...
    'The archive command must reject non-GNU tar.');
assert(contains(root_readme,'--format=ustar') && ...
    contains(root_readme,'--verbatim-files-from') && ...
    contains(root_readme,'--numeric-owner') && ...
    contains(root_readme,'--owner=0') && ...
    contains(root_readme,'--group=0') && ...
    contains(root_readme,"--mode='u=rwX,go=rX'") && ...
    contains(root_readme,'--no-acls') && ...
    contains(root_readme,'--no-xattrs') && ...
    contains(root_readme,'--no-selinux'), ...
    'The archive command must normalize Linux ownership and permissions.');
assert(contains(attributes, ...
    'runtime/bouchet_all_12_package_manifest.txt text eol=lf'), ...
    'The verbatim GNU tar manifest must remain LF on every checkout.');
archive_name = 'tc-smewn-v09-energy-farm-p-return-bouchet.tar.gz';
sidecar_name = [archive_name '.sha256.txt'];
assert(contains(root_readme, ...
    sprintf('sha256sum %s > %s',archive_name,sidecar_name)), ...
    'The archive command must write its SHA-256 sidecar.');
root_readme_lf = strrep(root_readme,sprintf('\r\n'),sprintf('\n'));
deployment_block = sprintf([ ...
    '```bash\n' ...
    'set -euo pipefail\n' ...
    '(cd .. && sha256sum -c %s)\n' ...
    'tar --no-same-owner -xzf ../tc-smewn-v09-energy-farm-p-return-bouchet.tar.gz\n' ...
    'test -r ''v2/T&C_Code/Inputs/Data_Kantola.mat''\n' ...
    'test -r ''v2/T&C_Code/Inputs/Data_Kantola_BG.mat''\n' ...
    'test -r ''v2/T&C_Code/Tests/run_post_legacy_equation_audit_tests.m''\n' ...
    'test -r ''v2/POST_LEGACY_EQUATION_AUDIT.md''\n' ...
    'MATLAB_MODULE=MATLAB/2025a TC_BOUCHET_ACCOUNT=pi_np363 bash runtime/submit_bouchet_all_12.sh\n' ...
    '```'],sidecar_name);
assert(contains(root_readme_lf,deployment_block), ...
    'The deployment block must fail before submitting an incomplete extraction.');
assert(contains(root_readme, ...
    "--exclude='v2/T&C_Code/Inputs/Data_Bruce_Field_*.mat'") && ...
    contains(root_readme, ...
    "--exclude='v2/T&C_Code/Inputs/Preprocess/Preprocess_Bruce_Field_ERA5.m'"), ...
    'The Energy Farm archive must omit Bruce-specific campaign data and code.');
readmes = [string(root_readme), ...
    string(fileread(fullfile(repo_root,'runtime', ...
    'Kantola_5yr_1D_Runs10to12_ScheduleFix_R2025a_Bouchet','README.md'))), ...
    string(fileread(fullfile(repo_root,'runtime', ...
    'Kantola_5yr_2D_Runs01to09_DenitPH7p8_Alpha1p3_Bouchet','README.md')))];
assert(all(contains(readmes,'Energy Farm')), ...
    'Every campaign runbook must identify the Energy Farm site.');
assert(contains(root_readme, ...
    'Bruce Field support is separate from this campaign'), ...
    'The root README must distinguish general Bruce support from this campaign.');
assert(contains(root_readme, ...
    'Bruce Field ERA5 forcing (full checkout only)'), ...
    'The campaign README must not present excluded Bruce tooling as available.');
assert(~any(contains(readmes,'sbatch ')), ...
    'Runbooks must not bypass the coordinated all-twelve controller.');

sbatch_1d = fileread(fullfile(repo_root,'runtime', ...
    'Kantola_5yr_1D_Runs10to12_ScheduleFix_R2025a_Bouchet', ...
    'submit_kantola_1d_runs_10_to_12.sbatch'));
sbatch_2d = fileread(fullfile(repo_root,'runtime', ...
    'Kantola_5yr_2D_Runs01to09_DenitPH7p8_Alpha1p3_Bouchet', ...
    'submit_kantola_2d_runs_01_to_09.sbatch'));
assert(contains(sbatch_1d,'#SBATCH --ntasks=3') && ...
    contains(sbatch_1d,'#SBATCH --mem=24G') && contains(sbatch_1d,'--mem=8G'));
assert(contains(sbatch_2d,'#SBATCH --array=1-9%9') && ...
    contains(sbatch_2d,'#SBATCH --cpus-per-task=6') && ...
    contains(sbatch_2d,'#SBATCH --mem=32G'));

launch_at = strfind(sbatch_1d,'for run_id in 10 11 12; do');
wait_at = strfind(sbatch_1d,'if ! wait "$pid"; then');
assert(~isempty(launch_at) && ~isempty(wait_at) && launch_at(1) < wait_at(1) && ...
    contains(sbatch_1d(launch_at(1):wait_at(1)-1),') &'), ...
    'Runs 10-12 must all launch before the first wait.');
run_token = regexp(sbatch_1d,'for run_id in ([0-9 ]+); do', ...
    'tokens','once');
run_ids = sscanf(run_token{1},'%d').';
array_tokens = regexp(sbatch_2d,'#SBATCH --array=(\d+)-(\d+)%\d+', ...
    'tokens','once');
n_2d = str2double(array_tokens{2})-str2double(array_tokens{1})+1;
assert(numel(run_ids)+n_2d == 12, ...
    'The coordinated launch must contain exactly twelve independent MATLAB runs.');
assert(~any(contains([sbatch_1d newline sbatch_2d], ...
        {'#SBATCH --gpus','#SBATCH --qos','#SBATCH --reservation', ...
         '#SBATCH --exclusive'})), ...
    'The CPU campaign must not request GPUs, policy tiers, reservations or whole nodes.');

cpus = 3 + 9*6;
memory_gb = 24 + 9*32;
assert(cpus == 57 && memory_gb == 312, ...
    'The coordinated production footprint is not 57 CPUs and 312 GB.');

fprintf('PASS: all twelve Bouchet runs share one validated eligibility barrier.\n');
end
