function test_bouchet_1d_rerun_configuration
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Static checks for the corrected Bouchet runs 10-12 campaign.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
v2_dir = fileparts(code_dir);
repo_root = fileparts(v2_dir);
campaign = 'Kantola_5yr_1D_Runs10to12_ScheduleFix_R2025a_Bouchet';
runtime_dir = fullfile(repo_root,'runtime',campaign);

wrapper = fileread(fullfile(runtime_dir, ...
    'Run_Bouchet_Kantola_1D_Task.m'));
assert(contains(wrapper,"version('-release')") && ...
       contains(wrapper,"'2025a'"), ...
    'The Bouchet wrapper must reject an unexpected MATLAB release.');
assert(contains(wrapper,"read_positive_integer('TC_RUN_ID')"));
assert(contains(wrapper,'run_id < 10') && contains(wrapper,'run_id > 12'));
assert(contains(wrapper,"'ParallelWorkers',0"));
assert(contains(wrapper,"'NDays',1826"));
assert(contains(wrapper,"'AppeloAlpha',1.3"));
assert(contains(wrapper,'TC_CKPT_FORCE_RESUME'));
assert(contains(wrapper,'Bouchet_Single_Thread_Runtime') && ...
       contains(wrapper,'validation_stamp.txt') && ...
       contains(wrapper,'Bouchet_Campaign_Validation_Fingerprint') && ...
       contains(wrapper,'StaleValidation'), ...
    'The R2025a production and single-thread gates are incomplete.');
assert(contains(wrapper,'Bouchet_Acquire_Run_Lock') && ...
       contains(wrapper,'locks'), ...
    'The wrapper must lock the treatment before it starts work.');
assert(contains(wrapper,'Bouchet_Check_Existing_Result') && ...
       contains(wrapper,"setenv('TC_VALIDATION_FINGERPRINT'"), ...
    'The wrapper must stamp its result and vet any existing one.');
%% The full fingerprint is tens of kilobytes and setenv refuses anything
%% over 32766 characters, so the stamp travels as a digest.
assert(contains(wrapper,'Bouchet_Fingerprint_Digest') && ...
       ~contains(wrapper,"setenv('TC_VALIDATION_FINGERPRINT',expected_stamp)"), ...
    'The validation stamp must reach the solver as a digest.');
digest = fileread(fullfile(runtime_dir,'Bouchet_Fingerprint_Digest.m'));
assert(contains(digest,'SHA-256') && contains(digest,'32766'), ...
    'The digest helper must hash the fingerprint and say why.');
assert(contains(wrapper,'SourceChangedDuringRun') && ...
       contains(wrapper,'MissingResult'), ...
    'The wrapper must recheck the source fingerprint after the run.');

validation = fileread(fullfile(runtime_dir, ...
    'Validate_Bouchet_1D_Campaign.m'));
assert(contains(validation,'run_post_legacy_equation_audit_tests') && ...
       contains(validation,'test_bouchet_linux_portability') && ...
       contains(validation,'Validate_Bouchet_1D_Preapplication_Identity') && ...
       contains(validation,'Bouchet_Campaign_Validation_Fingerprint') && ...
       contains(validation,'validation_stamp.txt') && ...
       contains(validation,'Bouchet_Write_Validation_Stamp'), ...
    'The R2025a validation entry point is incomplete.');

validator = fileread(fullfile(runtime_dir, ...
    'Validate_Bouchet_1D_Preapplication_Identity.m'));
assert(contains(validator,"run_ids = [10 11 12 12]") && ...
       contains(validator,"'NDays',315") && ...
       contains(validator,"'ParallelWorkers',0"), ...
    'The same-node discriminator must include every treatment and a calcite repeat.');
for field = {'Date','Pr','Ta','P','O','V','Ts','Tdp','Lk','T_H', ...
        'T_L','EG','LAI_L','B_L','PH_d','N2Oflx','LEAK_NO3', ...
        'LEAK_NH4','NavlI'}
    assert(contains(validator,['''' field{1} '''']), ...
        'The pre-application discriminator omits %s.',field{1});
end
assert(contains(validator,'isequaln') && ...
       contains(validator,'ERW_Application_Indices') && ...
       contains(validator,'M_rock_add') && ...
       contains(validator,'M_min'), ...
    'The discriminator must check exact states and the amendment boundary.');

sbatch = fileread(fullfile(runtime_dir, ...
    'submit_kantola_1d_runs_10_to_12.sbatch'));
assert(~contains(sbatch,'#SBATCH --array='), ...
    'The treatments must share one physical node, not use a Slurm array.');
assert(contains(sbatch,'#SBATCH --partition=day'));
assert(contains(sbatch,'#SBATCH --constraint=cpumodel:9575f'));
assert(contains(sbatch,'#SBATCH --nodes=1'));
assert(contains(sbatch,'#SBATCH --ntasks=3'));
assert(contains(sbatch,'#SBATCH --cpus-per-task=1'));
assert(contains(sbatch,'#SBATCH --mem=24G'));
assert(contains(sbatch,'#SBATCH --time=06:00:00'));
assert(contains(sbatch,'export TC_PARALLEL_WORKERS=0'));
assert(contains(sbatch,'export TC_CKPT_MINUTES=30'));
assert(contains(sbatch,'unset TC_CKPT_FORCE_RESUME'));
assert(contains(sbatch,'export OMP_NUM_THREADS=1'));
assert(contains(sbatch,'export MKL_NUM_THREADS=1'));
assert(contains(sbatch,'export OPENBLAS_NUM_THREADS=1'));
assert(contains(sbatch,'export TC_NUMERICAL_IDENTITY=') && ...
       contains(sbatch,'parallel_workers=0'), ...
    'The production numerical identity is missing.');
assert(contains(sbatch,'scontrol show node "$SLURMD_NODENAME"') && ...
       contains(sbatch,'lscpu') && contains(sbatch,'hostname') && ...
       contains(sbatch,'sha256sum'), ...
    'The job must record its hardware and source hashes.');
assert(contains(sbatch,'for run_id in 10 11 12') && ...
       contains(sbatch,'srun --exclusive') && ...
       contains(sbatch,'export TC_RUN_ID="$run_id"') && ...
       contains(sbatch,'wait "$pid"'), ...
    'Runs 10-12 must launch concurrently as exclusive tasks on one node.');
assert(~contains(sbatch,'compgen -G "$results_dir/TC_2D_run'), ...
    ['Whether an existing MAT may stand is a validation question; the ' ...
     'shell must not skip a run on a filename match alone.']);
assert(contains(sbatch,'MAIN_FRAME_BG_ERW_2D.m') && ...
       ~contains(sbatch,'MAIN_FRAME_BG_ERW_10mins.m'), ...
    'The startup hashes must cover the driver this campaign actually runs.');
assert(contains(sbatch,'TC_REBUILD_EQUIVALENCE') && ...
       contains(sbatch,'TC_CASE=5') && ...
       contains(sbatch,'TC_SCENARIO=EQUIV_1D_TMP') && ...
       contains(sbatch,'TC_NDAYS=10') && ...
       contains(sbatch,'TC_VALIDATE_ONLY') && ...
       contains(sbatch,'Validate_Bouchet_1D_Campaign') && ...
       contains(sbatch,'matlab -singleCompThread -batch'), ...
    'The R2025a equivalence-baseline rebuild path is missing.');

readme = fileread(fullfile(runtime_dir,'README.md'));
assert(contains(readme,'--cpus-per-task=6') && ...
       contains(readme,'TC_VALIDATE_ONLY=1') && ...
       contains(readme,'TC_REBUILD_EQUIVALENCE=1') && ...
       contains(readme,'PASS: Bouchet R2025a corrected 1-D validation') && ...
       contains(readme,'Do not submit the production job'), ...
    'The runbook must require baseline rebuild and validation before production.');

fingerprint = fileread(fullfile(code_dir, ...
    'Bouchet_Campaign_Validation_Fingerprint.m'));
assert(contains(fingerprint,'ERW_Checkpoint_Fingerprint') && ...
       contains(fingerprint,"version('-release')") && ...
       contains(fingerprint,"evalc('version -blas')") && ...
       contains(fingerprint,'maxNumCompThreads') && ...
       contains(fingerprint,"fullfile(code_dir,'Tests','*.m')") && ...
       contains(fingerprint,"fullfile(runtime_dir,'*.sbatch')") && ...
       contains(fingerprint, ...
           "fullfile(code_dir,'Tests','Fixtures','*.mat')") && ...
       contains(fingerprint,'TC_ERW_results_Kantola_crop_control.mat'), ...
    'The validation stamp must cover source, tests and numerical runtime.');
writer = fileread(fullfile(code_dir,'Bouchet_Write_Validation_Stamp.m'));
assert(contains(writer,'tempname') && contains(writer,'movefile') && ...
       contains(writer,"'f'"), ...
    'The validation stamp must be replaced atomically.');

%% Multithreaded BLAS reorders reductions, so the campaign is only
%% reproducible on one computational thread.  MATLAB owns MKL threading and
%% does not preserve MKL_NUM_THREADS through startup on Bouchet, so the gate
%% asserts maxNumCompThreads and sets the variables rather than trusting
%% them.
threads = fileread(fullfile(code_dir,'Bouchet_Single_Thread_Runtime.m'));
assert(contains(threads,'maxNumCompThreads') && ...
       contains(threads,'MatlabThreads') && ...
       contains(threads,'error('), ...
    'The single-thread gate must hard-fail on more than one thread.');
for name = {'OMP_NUM_THREADS','MKL_NUM_THREADS','OPENBLAS_NUM_THREADS'}
    assert(contains(threads,name{1}), ...
        'The single-thread gate omits %s.',name{1});
end
assert(contains(threads,'setenv'), ...
    'The gate must set the thread variables, not merely assert them.');

launcher = fileread(fullfile(v2_dir,'run','Run_One_Subfield.m'));
for field = {'matlab_version','matlab_release','blas','max_threads', ...
        'parallel_workers','numerical_identity','validation_fingerprint', ...
        'n_days','n_timesteps','n_columns','slurm_job_id', ...
        'slurm_step_id','slurm_restart_count','node'}
    assert(contains(launcher,['run_provenance.' field{1}]), ...
        'Saved result provenance omits %s.',field{1});
end

%% A resumed run must report every execution segment, not just the one that
%% happened to write the checkpoint it restored, and must honour the
%% options it was called with. test_campaign_resume_provenance exercises
%% both against a real run; this only checks the guards are still present.
driver = fileread(fullfile(code_dir,'MAIN_FRAME_BG_ERW_2D.m'));
assert(contains(driver,'keep_provenance') && ...
       contains(driver,'execution_segments') && ...
       contains(driver,'resumed_from_iteration'), ...
    'A resumed checkpoint must not overwrite the current run provenance.');
assert(contains(driver,'keep_opt'), ...
    'A resumed checkpoint must not overwrite the caller options.');

%% Filename wildcards cannot tell which code produced a MAT.
checker = fileread(fullfile(code_dir,'Bouchet_Check_Existing_Result.m'));
for identifier = {'StaleResult','UnprovenancedResult','UnreadableResult', ...
        'AmbiguousResult','WrongResultColumns','WrongResultHorizon'}
    assert(contains(checker,identifier{1}), ...
        'The existing-result gate omits %s.',identifier{1});
end
locker = fileread(fullfile(code_dir,'Bouchet_Acquire_Run_Lock.m'));
assert(contains(locker,'MATLAB:MKDIR:DirectoryExists') && ...
       contains(locker,'RunLocked') && contains(locker,'onCleanup'), ...
    'The run lock must rely on atomic directory creation.');

fprintf('PASS: Bouchet corrected runs 10-12 configuration\n');
end
