function test_kantola_5yr_2d_configuration
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Exact configuration contract for the five-year 2-D comparison.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

test_dir = fileparts(mfilename('fullpath'));
v2 = fileparts(fileparts(test_dir));
repo_root = fileparts(v2);
tag = 'Kantola_5yr_2D_WholeField_Control_Basalt_Calcite_DenitPH7p8_Alpha1p3';
launcher_dir = fullfile(repo_root,'runtime',tag);
addpath(fullfile(v2,'run'),fullfile(v2,'T&C_Code'),launcher_dir);

old_folder = pwd;
old_checkpoint_minutes = getenv('TC_CKPT_MINUTES');
old_force_resume = getenv('TC_CKPT_FORCE_RESUME');
cleanup = onCleanup(@() restore_test_environment(old_folder, ...
    old_checkpoint_minutes,old_force_resume)); %#ok<NASGU>
setenv('TC_CKPT_MINUTES','37');
setenv('TC_CKPT_FORCE_RESUME','test-sentinel');

[output,plan] = evalc('Launch_Kantola_5yr_2D_WholeField_DenitPH7p8(true)');
R = Run_Matrix_12();
whole_field = R(1:3);
vertical_1d = R(10:12);

assert(isequal([plan.run_id],1:3), ...
    'The comparison must contain only whole-field runs 1 to 3.');
assert(isequal({whole_field.treatment},{vertical_1d.treatment}) && ...
       isequal([whole_field.case_number],[vertical_1d.case_number]), ...
    'The 2-D treatments must use the same workbook cases as runs 10 to 12.');
assert(all(strcmp({whole_field.layout},'whole_field')) && ...
       all([whole_field.use_subdomains]), ...
    'Runs 1 to 3 must retain the whole-field 2-D layout.');
assert(isequal([whole_field.biogeo_depth_mm],[300 300 300]), ...
    'All runs must use the 300 mm active biogeochemical depth.');
assert(~whole_field(1).apply_main && ~whole_field(1).apply_margin && ...
       all([whole_field(2:3).apply_main]) && ...
       all([whole_field(2:3).apply_margin]), ...
    'Control and whole-field treatment placement are incorrect.');

topo = Build_Cell_Topology(60,5,2,2);
is_main = strcmp(topo.cell_region,'main');
assert(topo.N_cells == 12 && topo.N_edges == 20, ...
    'The configured 2-D topology must contain 12 cells and 20 edges.');
assert(abs(sum(topo.cell_area_m2)-3600) < 1e-10 && ...
       abs(sum(topo.cell_area_m2(is_main))-2500) < 1e-10 && ...
       abs(sum(topo.cell_area_m2(~is_main))-1100) < 1e-10, ...
    'The field and buffer areas do not close to the 60 m square domain.');

result_dir = fullfile(v2,'SIM','Subfield_12',tag);
log_dir = fullfile(v2,'logs','Subfield_12',tag);
assert(all(startsWith({plan.result_file},result_dir)) && ...
       all(startsWith({plan.log_file},log_dir)), ...
    'Results and logs must use the isolated descriptive campaign folders.');
expected_files = { ...
    'TC_2D_run01_control__whole_field__grid2x2__alpha1p3__1826d__from20160101.mat', ...
    'TC_2D_run02_basalt__whole_field__grid2x2__alpha1p3__1826d__from20160101.mat', ...
    'TC_2D_run03_calcite__whole_field__grid2x2__alpha1p3__1826d__from20160101.mat'};
actual_files = cell(size(plan));
for k = 1:numel(plan)
    [~,name,ext] = fileparts(plan(k).result_file);
    actual_files{k} = [name ext];
end
assert(isequal(actual_files(:).',expected_files), ...
    'The final result names do not encode the intended 2-D campaign.');
assert(all(contains({plan.command},'''NDays'',1826')) && ...
       all(contains({plan.command},'''GridNx'',2')) && ...
       all(contains({plan.command},'''GridNy'',2')) && ...
       all(contains({plan.command},'''AppeloAlpha'',1.3')) && ...
       all(contains({plan.command},'''StartDate''')), ...
    'A scientific run option was not forwarded to every worker.');
assert(contains(output,'max concurrent: 2') && ...
       contains(output,'max runtime per run: 168 h') && ...
       contains(output,'forced checkpoint resume: disabled'), ...
    'The launcher resource or checkpoint policy changed.');
assert(numel(unique({plan.preference_directory})) == 3 && ...
       numel(unique({plan.temporary_directory})) == 3, ...
    'Each worker must have isolated MATLAB preference and TEMP folders.');
assert(strcmp(getenv('TC_CKPT_MINUTES'),'37') && ...
       strcmp(getenv('TC_CKPT_FORCE_RESUME'),'test-sentinel') && ...
       strcmp(pwd,old_folder), ...
    'The launcher did not restore the calling MATLAB environment.');

launcher_source = fileread(fullfile(launcher_dir, ...
    'Launch_Kantola_5yr_2D_WholeField_DenitPH7p8.m'));
assert(contains(launcher_source,"setenv('TC_CKPT_FORCE_RESUME','')") && ...
       contains(launcher_source,"'Overwrite',false") && ...
       contains(launcher_source,"'MaxConcurrent',2") && ...
       contains(launcher_source,tag), ...
    'Forced resume, overwrite protection or the memory limit changed.');

fprintf('PASS: five-year 2-D comparison configuration is locked and isolated.\n');
end

function restore_test_environment(old_folder,checkpoint_minutes,force_resume)
cd(old_folder);
setenv('TC_CKPT_MINUTES',checkpoint_minutes);
setenv('TC_CKPT_FORCE_RESUME',force_resume);
end
