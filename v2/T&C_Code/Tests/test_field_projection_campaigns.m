end

function [identity,knobs,span] = name_parts(run_name,ssp,calcite_case,field_tag,K,number_tag)
%% A result tag as Run_One_Subfield strings it together.
identity = [run_name '__' ssp];
if ~isempty(calcite_case); identity = sprintf('%s__case%d',identity,calcite_case); end
identity = [identity '__' field_tag];
knobs = ['__alpha' number_tag(K.AppeloAlpha) '__logkh' ...
    strjoin(arrayfun(number_tag,K.AppeloLogKH,'UniformOutput',false),'_') ...
    '__knmaxd' number_tag(K.KNmaxd)];
if ~isempty(K.BiogeoOverrides); knobs = [knobs '__bg12fields_0a1b2c3d']; end
if ~isempty(K.DissolutionFactor); knobs = [knobs '__fd' number_tag(K.DissolutionFactor)]; end
if K.SaturationExponent ~= 1; knobs = [knobs '__sexp' number_tag(K.SaturationExponent)]; end
knobs = [knobs '__kbotfree'];
span = '__12784d__from20160101';
end

function assert_error(fun,identifier)
try
    fun();
catch ME
    assert(strcmp(ME.identifier,identifier), ...
        'Expected %s, got %s: %s',identifier,ME.identifier,ME.message);
    return
end
error('Expected error %s was not raised.',identifier);
end
