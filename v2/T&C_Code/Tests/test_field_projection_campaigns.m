function test_field_projection_campaigns
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Pin the 35-year campaigns on a field grid: the central SSP runs
%% (runtime/Field_SSP_2D) and the lower and upper sets of the uncertainty
%% ensemble (runtime/Field_Uncertainty_2D). Their grid helper, the campaign
%% definition, the file-name bound every field-grid ensemble name needs,
%% and the gates of the tasks, batch files and controllers.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

test_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(test_dir);
repo_root = fileparts(fileparts(code_dir));
central_dir = fullfile(repo_root,'runtime','Field_SSP_2D');
ensemble_dir = fullfile(repo_root,'runtime','Field_Uncertainty_2D');
addpath(code_dir,fullfile(repo_root,'v2','run'),central_dir,ensemble_dir, ...
    fullfile(repo_root,'runtime','Uncertainty_1D'),fullfile(repo_root,'runtime','Base_1D'));
for file = {fullfile(central_dir,'submit_field_ssp_2d.sh'), ...
        fullfile(central_dir,'submit_field_ssp_2d.sbatch'), ...
        fullfile(central_dir,'Run_Field_SSP_2D_Task.m'), ...
        fullfile(central_dir,'Field_Campaign_Grid.m'), ...
        fullfile(central_dir,'Check_Lateral_Conservation.m'), ...
        fullfile(central_dir,'README.md'), ...
        fullfile(ensemble_dir,'submit_field_uncertainty.sh'), ...
        fullfile(ensemble_dir,'submit_field_uncertainty.sbatch'), ...
        fullfile(ensemble_dir,'Run_Field_Uncertainty_Task.m'), ...
        fullfile(ensemble_dir,'Field_Uncertainty_Campaign.m'), ...
        fullfile(ensemble_dir,'README.md'), ...
        fullfile(repo_root,'v2','run','Bounded_File_Tag.m')}
    assert(isfile(file{1}),'%s is missing.',file{1});
end
assert(isequal(fileread(fullfile(central_dir,'Check_Lateral_Conservation.m')), ...
    fileread(fullfile(repo_root,'runtime','Field_2D','Check_Lateral_Conservation.m'))), ...
    'The field SSP campaign must carry a byte copy of the 2-D conservation check.');

%% ---------------------------------------------------------------------
%% File names: 255 characters at most, and unchanged when they fit.
%% ---------------------------------------------------------------------
P = Campaign_Parameters;
members = Uncertainty_Members;
number_tag = @(v) strrep(sprintf('%.12g',v),'.','p');
%% The longest grid tag of the Kantola grids (their build records: the
%% control boundary, 10 m squares, the 20 m margin, the DEM at 10 m).
field_tag = 'field_kantola_control_10m__cell10m__margin20__dem10';
longest = 0;
for m = 1:numel(members)
    K = Uncertainty_Knobs(members(m),P);
    [identity,knobs,span] = name_parts('calcite__margin_prairie','ssp585',8,field_tag,K,number_tag);
    tag = [identity knobs span];
    for prefix = {'TC_2D_run09_','ckpt_run09_'}
        bounded = Bounded_File_Tag(tag,numel(identity),numel(identity)+numel(knobs),prefix{1},'.mat');
        name = [prefix{1} bounded '.mat'];
        assert(numel(name) <= 255,'A field-grid name has %d characters.',numel(name));
        if numel([prefix{1} tag '.mat']) <= 255
            assert(strcmp(bounded,tag),'A name that fits must stay as it is (%s).',members(m).tag);
        else
            assert(startsWith(bounded,identity) && endsWith(bounded,span) && ...
                ~isempty(regexp(bounded,'__knobs[0-9a-f]{12}__12784d__from20160101$','once')), ...
                'A long name keeps its run, scenario, case, grid and span, its knobs a digest.');
            assert(strcmp(Bounded_File_Tag(tag,numel(identity),numel(identity)+numel(knobs), ...
                prefix{1},'.mat'),bounded),'The bound must be deterministic.');
        end
        longest = max(longest,numel(name));
    end
    if ~members(m).reused
        assert(numel(['TC_2D_run09_' tag '.mat']) > 255, ...
            'The %s set''s field-grid name must need the bound (else this test is stale).',members(m).tag);
    else
        assert(numel(['TC_2D_run09_' tag '.mat']) <= 255, ...
            'The central field run''s name must fit as it is.');
    end
end
fprintf('Longest bounded field-grid name: %d characters.\n',longest);
%% The digest tells sets apart and keeps the scenario and case readable.
KL = Uncertainty_Knobs(members(2),P); KU = Uncertainty_Knobs(members(3),P);
[il,kl,sl] = name_parts('basalt__whole_field','ssp126',[],field_tag,KL,number_tag);
[iu,ku,su] = name_parts('basalt__whole_field','ssp126',[],field_tag,KU,number_tag);
bl = Bounded_File_Tag([il kl sl],numel(il),numel(il)+numel(kl),'TC_2D_run02_','.mat');
bu = Bounded_File_Tag([iu ku su],numel(iu),numel(iu)+numel(ku),'TC_2D_run02_','.mat');
assert(~strcmp(bl,bu),'The lower and upper names must differ.');
C = struct('scenario','ssp126','calcite_case',[],'n_days',12784,'n_columns',3, ...
    'last_application_year',2050);
p = struct('campaign','Field_Uncertainty_2D_35yr_ssp126__grid','validation_fingerprint','d', ...
    'n_days',12784,'n_columns',3,'last_application_year',2050,'KNmaxd',KU.KNmaxd, ...
    'Kbot',KU.Kbot,'biogeo_overrides',KU.BiogeoOverrides,'dissolution_factor',KU.DissolutionFactor, ...
    'saturation_exponent',KU.SaturationExponent,'AppeloAlpha',repmat(KU.AppeloAlpha,3,1), ...
    'AppeloLogKH',repmat(KU.AppeloLogKH,3,1));
assert(Uncertainty_Result_Matches(p,['TC_2D_run02_' bu '.mat'],C,KU,p.campaign,'d'), ...
    'A bounded name must still carry the scenario and case the ensemble checks.');
assert_error(@() Bounded_File_Tag(repmat('x',1,260),0,0,'TC_2D_run01_','.mat'), ...
    'Bounded_File_Tag:NameTooLong');
assert_error(@() Bounded_File_Tag('abc',2,1,'p','.mat'),'Bounded_File_Tag:BadInput');
short = 'control__whole_field__alpha3p4__knmaxd0p0048__kbotfree__1826d__from20160101';
assert(strcmp(Bounded_File_Tag(short,20,50,'TC_2D_run01_','.mat'),short), ...
    'A short name must not change.');
driver = fileread(fullfile(repo_root,'v2','run','Run_One_Subfield.m'));
assert(contains(driver,['ckpt_tag = Bounded_File_Tag(ckpt_tag,ckpt_knobs_from,ckpt_knobs_to, ...' newline ...
    '    sprintf(''ckpt_run%02d_'',R.id),''.mat'');']) && ...
    contains(driver,'tag = Bounded_File_Tag(tag,knobs_from,knobs_to,sprintf(''TC_2D_run%02d_'',R.id),''.mat'');') && ...
    numel(strfind(driver,'ckpt_knobs_from = numel(ckpt_tag);')) == 1 && ...
    numel(strfind(driver,'knobs_from = numel(tag);')) == 1, ...
    'Run_One_Subfield must bound its checkpoint and result names.');
ckpt_bound = strfind(driver,'ckpt_tag = Bounded_File_Tag(');
ckpt_file = strfind(driver,'ERW_ckpt_file = fullfile(ckpt_dir, ...');
result_bound = strfind(driver,'tag = Bounded_File_Tag(tag,');
result_file = strfind(driver,'result_file = fullfile(fl_save,');
assert(isscalar(ckpt_bound) && isscalar(ckpt_file) && ckpt_bound < ckpt_file && ...
    isscalar(result_bound) && isscalar(result_file) && result_bound < result_file, ...
    'The bound must apply before the names are formed.');

%% ---------------------------------------------------------------------
%% The grid helper.
%% ---------------------------------------------------------------------
prefix = 'Test_Field';
folder = tempname;
mkdir(folder);
cleanup_folder = onCleanup(@() rmdir(folder,'s'));
topo = struct('N_cells',3,'field_grid_build',struct('cell_size_m',10), ...
    'cell_size_m',10,'topography_attached',true); %#ok<NASGU>
grid_file = fullfile(folder,'test_grid_10m.mat');
save(grid_file,'topo');
env = {'TC_FIELD_TOPOLOGY','TC_SSP','TC_CALCITE_CASE','TC_FIELD_RUNS','TC_FIELD_WORKERS', ...
    'SLURM_MEM_PER_NODE','TC_ERW_KERNEL'};
saved = cellfun(@getenv,env,'UniformOutput',false);
restore = onCleanup(@() cellfun(@setenv,env,saved)); %#ok<NASGU>
setenv('TC_FIELD_TOPOLOGY',grid_file);
[file,name] = Field_Campaign_Grid('read',repo_root,prefix);
assert(strcmp(name,'test_grid_10m') && isfile(file),'The grid file must resolve.');
loaded = Field_Campaign_Grid('load',file,prefix);
assert(loaded.N_cells == 3,'The grid must load.');
setenv('TC_FIELD_TOPOLOGY',fullfile(folder,'absent.mat'));
assert_error(@() Field_Campaign_Grid('read',repo_root,prefix),[prefix ':MissingTopology']);
bad_name = fullfile(folder,'bad-name.mat');
copyfile(grid_file,bad_name);
setenv('TC_FIELD_TOPOLOGY',bad_name);
assert_error(@() Field_Campaign_Grid('read',repo_root,prefix),[prefix ':BadTopologyName']);
setenv('TC_FIELD_TOPOLOGY',fullfile(central_dir,'Field_Campaign_Grid.m'));
assert_error(@() Field_Campaign_Grid('read',repo_root,prefix),[prefix ':TopologyInsideRoot']);
not_grid = fullfile(folder,'not_grid.mat');
x = 1; %#ok<NASGU>
save(not_grid,'x');
assert_error(@() Field_Campaign_Grid('load',not_grid,prefix),[prefix ':BadTopology']);
setenv('TC_FIELD_TOPOLOGY',grid_file);
%% The grid's provenance: the file, its SHA-256, the topography switch and
%% the square count.
fid = fopen(grid_file,'rb'); bytes = fread(fid,Inf,'*uint8'); fclose(fid);
md = javaMethod('getInstance','java.security.MessageDigest','SHA-256');
md.update(typecast(bytes,'int8'));
sha = lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
good = struct('field_topology_file',file,'field_topology_file_sha256',sha, ...
    'opt_dem',1,'n_columns',3);
Field_Campaign_Grid('provenance',good,file,loaded,prefix);
assert_error(@() Field_Campaign_Grid('provenance',setfield(good,'n_columns',4),file,loaded,prefix), ...
    [prefix ':WrongGridProvenance']); %#ok<SFLD>
assert_error(@() Field_Campaign_Grid('provenance',setfield(good,'opt_dem',0),file,loaded,prefix), ...
    [prefix ':WrongGridProvenance']); %#ok<SFLD>
assert_error(@() Field_Campaign_Grid('provenance',setfield(good,'field_topology_file_sha256', ...
    repmat('0',1,64)),file,loaded,prefix),[prefix ':WrongGridProvenance']); %#ok<SFLD>
%% Run lists as the controllers pass them.
assert(isequal(Field_Campaign_Grid('runs','1,4,7',[],prefix),[1 4 7]) && ...
    isequal(Field_Campaign_Grid('runs','3,6,9',8,prefix),[3 6 9]),'Run lists must parse.');
assert_error(@() Field_Campaign_Grid('runs','2,3',8,prefix),[prefix ':BadRunList']);
assert_error(@() Field_Campaign_Grid('runs','1,1',[],prefix),[prefix ':BadRunList']);
assert_error(@() Field_Campaign_Grid('runs','1-9',[],prefix),[prefix ':BadRunList']);
assert_error(@() Field_Campaign_Grid('runs','10',[],prefix),[prefix ':BadRunList']);
%% Memory: package y's daily arrays and ERW day summaries, whole at the end.
floor_369 = Field_Campaign_Grid('memory',369,12784);
floor_340 = Field_Campaign_Grid('memory',340,12784);
assert(abs(floor_369-(4+8*763*12785*369/2^30)) < 1e-9 && floor_369 > 30 && floor_369 < 32 && ...
    floor_340 < floor_369,'The memory floor must be package y''s figure (about 31 GiB on 369 squares).');
setenv('SLURM_MEM_PER_NODE',sprintf('%d',24*1024));
assert_error(@() Field_Campaign_Grid('check_memory',369,12784,prefix),[prefix ':InsufficientMemory']);
setenv('SLURM_MEM_PER_NODE',sprintf('%d',96*1024));
Field_Campaign_Grid('check_memory',369,12784,prefix);
%% Package z's ERW kernels: matlab unless fast is asked for; never mex on
%% a field run's thread pool; the result must record the one it ran.
setenv('TC_ERW_KERNEL','');
assert(strcmp(Field_Campaign_Grid('kernel',prefix),'matlab'),'Unset is the original code.');
setenv('TC_ERW_KERNEL',' Fast ');
assert(strcmp(Field_Campaign_Grid('kernel',prefix),'fast'),'fast is read as written.');
for bad = {'mex','faster'}
    setenv('TC_ERW_KERNEL',bad{1});
    assert_error(@() Field_Campaign_Grid('kernel',prefix),[prefix ':BadKernel']);
end
setenv('TC_ERW_KERNEL','');
Field_Campaign_Grid('kernel_provenance',struct('erw_kernel','fast'),'fast',prefix);
assert_error(@() Field_Campaign_Grid('kernel_provenance',struct('erw_kernel','matlab'),'fast',prefix), ...
    [prefix ':WrongKernel']);
assert_error(@() Field_Campaign_Grid('kernel_provenance',struct(),'matlab',prefix), ...
    [prefix ':WrongKernel']);

%% ---------------------------------------------------------------------
%% The ensemble on a field grid.
%% ---------------------------------------------------------------------
setenv('TC_SSP','ssp245'); setenv('TC_CALCITE_CASE',''); setenv('TC_FIELD_RUNS','2,3,5');
setenv('TC_FIELD_WORKERS','32');
C = Field_Uncertainty_Campaign;
assert(strcmp(C.tag,'Field_Uncertainty_2D_35yr_ssp245__test_grid_10m') && ...
    strcmp(C.original_tag,'Field_SSP_2D_35yr_ssp245__test_grid_10m') && ...
    C.n_days == 12784 && C.last_application_year == 2050 && C.n_columns == 3 && ...
    C.workers == 3 && isequal(C.runs,[2 3 5]) && ...
    isequal(C.options,{'FieldTopologyFile',file,'Scenario','ssp245','LastApplicationYear',2050}), ...
    'A field ensemble runs the field SSP campaign''s runs on its grid.');
assert(numel(C.elements) == 6 && isequal([C.elements.run_id],[2 3 5 2 3 5]) && ...
    isequal(arrayfun(@(e) e.member.tag,C.elements,'UniformOutput',false), ...
    {'lower','lower','lower','upper','upper','upper'}),'Elements must be member-major.');
assert(any(contains(C.dependencies,'Data_Kantola_ssp245.mat')) && ...
    any(strcmp(C.dependencies,file)) && any(contains(C.dependencies,'Field_SSP_2D')) && ...
    any(contains(C.dependencies,'Uncertainty_1D')),'The forcing, grid and borrowed code are in the gate.');
setenv('TC_CALCITE_CASE','8'); setenv('TC_FIELD_RUNS','');
C = Field_Uncertainty_Campaign;
assert(strcmp(C.tag,'Field_Uncertainty_2D_35yr_ssp245_case8__test_grid_10m') && ...
    isequal(C.runs,[3 6 9]) && isequal(C.options(end-1:end),{'CalciteCase',8}), ...
    'The 5 t/ha arm runs calcite runs 3, 6 and 9.');
setenv('TC_FIELD_RUNS','2');
assert_error(@() Field_Uncertainty_Campaign,'Kantola_FieldUncertainty:BadRunList');
setenv('TC_CALCITE_CASE',''); setenv('TC_FIELD_RUNS',''); setenv('TC_FIELD_WORKERS','1');
assert_error(@() Field_Uncertainty_Campaign,'Kantola_FieldUncertainty:BadWorkers');
setenv('TC_FIELD_WORKERS','32'); setenv('TC_SSP','ssp370');
assert_error(@() Field_Uncertainty_Campaign,'Kantola_FieldUncertainty:BadScenario');
setenv('TC_SSP','ssp245');

%% ---------------------------------------------------------------------
%% Tasks, batch files and controllers.
%% ---------------------------------------------------------------------
task = fileread(fullfile(central_dir,'Run_Field_SSP_2D_Task.m'));
task_tokens = {'Bouchet_Single_Thread_Runtime(prefix);', ...
    'n_days = 12784;','last_application_year = 2050;', ...
    "campaign_tag = sprintf('Field_SSP_2D_35yr_%s%s__%s',scenario,case_suffix,topology_name);", ...
    "if ~strcmp(getenv('TC_CKPT_MINUTES'),'120')", ...
    'workers = Resolve_2D_Parfor_Workers(n_columns);', ...
    "Field_Campaign_Grid('check_memory',n_columns,n_days,prefix);", ...
    "error([prefix ':StaleValidation']", ...
    'Bouchet_Acquire_Run_Lock(', ...
    "'FieldTopologyFile',topology_file, ...", ...
    "'AppeloAlpha',P.AppeloAlpha,'AppeloLogKH',P.AppeloLogKH, ...", ...
    "'KNmaxd',P.KNmaxd,'Kbot',P.Kbot, ...", ...
    "'Scenario',scenario,'LastApplicationYear',last_application_year};", ...
    "error([prefix ':SourceChangedDuringRun']", ...
    'Assert_Base_Provenance(saved.run_provenance,run_id,n_columns,workers, ...', ...
    "Field_Campaign_Grid('provenance',saved.run_provenance,topology_file,topo,prefix);", ...
    "kernel = Field_Campaign_Grid('kernel',prefix);", ...
    "Field_Campaign_Grid('kernel_provenance',saved.run_provenance,kernel,prefix);", ...
    "Check_Lateral_Conservation(result_file,prefix);", ...
    'run_post_legacy_equation_audit_tests(1);', ...
    'test_bouchet_linux_portability({campaign_dir,one_d_dir});'};
for k = 1:numel(task_tokens)
    assert(contains(task,task_tokens{k}),'The field SSP task omits %s.',task_tokens{k});
end
assert(isscalar(strfind(task,'Bouchet_Acquire_Run_Lock(')) && ...
    all(strfind(task,'Bouchet_Acquire_Run_Lock(') < ...
    strfind(task,'Bouchet_Check_Existing_Result( ...')),'The lock must come before the result check.');
ensemble_task = fileread(fullfile(ensemble_dir,'Run_Field_Uncertainty_Task.m'));
